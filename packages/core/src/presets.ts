export function getPreset(id: string): ProviderPreset | undefined {
  return PROVIDER_PRESETS.find((p) => p.id === id)
}

export function resolvePresetBaseUrl(preset: Pick<ProviderPreset, 'baseUrl'>, hubUrl: string): string {
  return preset.baseUrl.replace('{hub}', hubUrl.replace(/\/+$/, ''))
}
